-- Reproduces the live InterVous database (2026-10-17) inside a fresh supabase/postgres container.
-- Run as supabase_admin (superuser): it stubs what storage-api would create, then builds the
-- public tables AS postgres, the role the Supabase SQL editor uses, so the migration runs with
-- the same privileges as on the live project.
--
-- Variants (psql -v name=value), used by scripts/test-sql.sh:
--   id_type        integer (live) | bigint
--   date_type      text (live)    | date | timestamptz
--   strict         0 | 1   1 = legacy columns NOT NULL, a created_at column and two pre-existing triggers on jobs
--   storage_owner  1 | 0   0 = postgres may not create policies on storage.objects ("must be owner"),
--                          done by emptying supautils.policy_grants
--   conflict       0 | 1   1 = a table named job_overview already exists, so the migration fails
--                          late (section 7); used to prove the single transaction leaves no trace
\set ON_ERROR_STOP 1
\if :{?id_type}
\else
  \set id_type integer
\endif
\if :{?date_type}
\else
  \set date_type text
\endif
\if :{?strict}
\else
  \set strict 0
\endif
\if :{?storage_owner}
\else
  \set storage_owner 1
\endif
\if :{?conflict}
\else
  \set conflict 0
\endif

-- stubs for what storage-api and the live project already have
create table if not exists storage.buckets(id text primary key, name text not null, owner uuid, public boolean default false,
  file_size_limit bigint, allowed_mime_types text[], created_at timestamptz default now(), updated_at timestamptz default now());
create table if not exists storage.objects(id uuid primary key default gen_random_uuid(), bucket_id text references storage.buckets(id), name text, owner uuid, created_at timestamptz default now());
alter table storage.objects enable row level security;
create or replace function storage.foldername(name text) returns text[] language plpgsql as $$
declare _parts text[]; begin select string_to_array(name, '/') into _parts; return _parts[1:array_length(_parts,1)-1]; end $$;
grant usage on schema storage to authenticated, anon, postgres;
grant all on storage.objects, storage.buckets to authenticated, postgres;
alter table storage.objects owner to supabase_storage_admin;
alter table storage.buckets owner to supabase_storage_admin;
insert into storage.buckets(id, name, public) values ('user_avatars', 'user_avatars', true);
