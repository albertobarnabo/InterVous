create table public.companies(id uuid primary key default gen_random_uuid(), name text not null, website text, logo_url text, created_by uuid);  -- live has no created_at
alter table public.companies enable row level security;
create policy c_all on public.companies for all to authenticated using (true) with check (true);
grant all on public.companies to authenticated;
create table public.jobs(id :id_type generated by default as identity primary key, user_id uuid references auth.users(id),
  company_name text, role text, location text, application_date :date_type, status text, stage text, url text);
\if :strict
-- plausible live variant: NOT NULL legacy columns, a created_at column, user_id defaulting to auth.uid(),
-- and triggers that already exist on jobs (one before, one after)
alter table public.jobs
  alter column company_name set not null, alter column role set not null, alter column location set not null,
  alter column application_date set not null, alter column status set not null, alter column stage set not null,
  alter column url set not null, alter column user_id set not null, alter column user_id set default auth.uid(),
  add column created_at timestamptz not null default now();
create function public.set_job_user_id() returns trigger language plpgsql as $$
begin new.user_id := coalesce(new.user_id, auth.uid()); return new; end $$;
create trigger on_job_insert before insert on public.jobs for each row execute function public.set_job_user_id();
create table public.jobs_audit(id bigint generated always as identity primary key, job_id bigint, op text, at timestamptz default now());
create function public.audit_job() returns trigger language plpgsql security definer set search_path = public as $$
begin insert into public.jobs_audit(job_id, op) values (new.id, tg_op); return null; end $$;
create trigger zz_audit after insert or update on public.jobs for each row execute function public.audit_job();
\endif
alter table public.jobs enable row level security;
create policy j_sel on public.jobs for select to authenticated using (user_id = auth.uid());
create policy j_ins on public.jobs for insert to authenticated with check (user_id = auth.uid());
create policy j_upd on public.jobs for update to authenticated using (user_id = auth.uid());
create policy j_del on public.jobs for delete to authenticated using (user_id = auth.uid());
grant all on public.jobs to authenticated;
